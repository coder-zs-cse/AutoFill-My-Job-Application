/**
 * ADAPTER between JS (src/core/native/specs/NativeFillmate.ts) and the autofill facade.
 * It only translates types and threads. Zero business logic: if you are writing an `if` about
 * matching or sessions here, it belongs in the autofill module.
 *
 * `NativeFillmateSpec` is GENERATED by RN codegen from the TS spec (codegenConfig in package.json).
 * Verify method signatures against the generated file after the first build.
 */
class FillmateModule(reactContext: ReactApplicationContext) : NativeFillmateSpec(reactContext) {
    private val autofill = FillmateAutofill(reactContext)
    private val io = Executors.newSingleThreadExecutor()

    override fun getName() = NAME

    private fun async(promise: Promise, block: () -> Any?) {
        io.execute {
            try { promise.resolve(block()) } catch (e: Throwable) { promise.reject("FILLMATE_NATIVE", e.message, e) }
        }
    }

    // --- session (phase 2: delegate to SessionStore via the facade) ---
    override fun saveSession(accessToken: String, refreshToken: String, userId: String, promise: Promise) =
        async(promise) { TODO("phase 2") }
    override fun getAccessToken(promise: Promise) = async(promise) { null }
    override fun refreshSession(promise: Promise) = async(promise) { null }
    override fun clearSession(promise: Promise) = async(promise) { TODO("phase 2") }

    // --- kb snapshot ---
    override fun syncKb(promise: Promise) = async(promise) { autofill.syncKb().toDouble() }
    override fun getKbVersion(promise: Promise) = async(promise) { autofill.kbVersion().toDouble() }

    // --- playground: same resolver as the AutofillService ---
    override fun resolveForPlayground(label: String, promise: Promise) =
        async(promise) { autofill.resolveForPlayground(label)?.toJson()?.toString() }

    // --- onboarding / settings ---
    override fun isAutofillServiceEnabled(promise: Promise) = async(promise) { autofill.isServiceEnabled() }
    override fun openAutofillSettings() = autofill.openServiceSettings()

    companion object { const val NAME = "Fillmate" }
}

/** Shape must match `PlaygroundTrace` in src/core/native/fillmateNative.ts. */
private fun ResolutionTrace.toJson(): JSONObject {
    val r = result
    return JSONObject()
        .put("label", label)
        .put("normalizedTokens", JSONArray(normalizedTokens))
        .put("qualifiers", JSONArray(qualifiers.toList()))
        .put("tier", when (r) { is MatchResult.Alias -> "alias"; is MatchResult.Semantic -> "semantic"; MatchResult.NoMatch -> "none" })
        .put("questionId", when (r) { is MatchResult.Alias -> r.questionId; is MatchResult.Semantic -> r.questionId; else -> JSONObject.NULL })
        .put("matchedAlias", (r as? MatchResult.Alias)?.alias ?: JSONObject.NULL)
        .put("answer", when (r) { is MatchResult.Alias -> r.answer; is MatchResult.Semantic -> r.answer; else -> JSONObject.NULL })
        .put("margin", (r as? MatchResult.Semantic)?.margin ?: JSONObject.NULL)
        .put("blocked", JSONArray(blocked.map {
            JSONObject().put("questionId", it.questionId).put("alias", it.alias).put("missingQualifier", it.missingQualifier)
        }))
        .put("semanticCandidates", JSONArray(semanticCandidates.map {
            JSONObject().put("questionId", it.questionId).put("score", it.score).put("blocked", it.blocked)
        }))
}
